/* ============================================================================
   POSTGRES INIT DB — MeterWorklog (MWL) / MWLTimesheet
   ============================================================================
   Straight syntax conversion of this repo's current MSSQL schema dump
   (previously the content of this file) into PostgreSQL DDL. Table shapes,
   column order, defaults, and constraints are preserved 1:1 from the source;
   only MSSQL-specific syntax is translated:

     - int identity                    -> INTEGER GENERATED BY DEFAULT AS IDENTITY
     - nvarchar(n) / nchar(n) / char   -> VARCHAR(n) / CHAR(n) / CHAR(1)
       (Postgres text types are UTF-8 natively; there is no separate
       "national character" type to map to)
     - datetime / datetime2            -> TIMESTAMP
     - getdate() / getdate() default   -> now() / CURRENT_DATE (for the DATE column)
     - bit                             -> BOOLEAN (0/1 -> FALSE/TRUE)
     - named MSSQL DEFAULT/PK/FK constraint identifiers (e.g. DF_Allowance_date,
       PK__Employee__...) are dropped where Postgres doesn't need them to be
       named; the one CHECK constraint whose name is referenced elsewhere in
       this repo's tooling (CK__worklogs__status__534D60F1) is preserved.
     - computed columns (`hours`, `overtime_hours`, `regular_hours` on
       worklogs) using DATEDIFF(MINUTE, a, b) are translated to
       EXTRACT(EPOCH FROM (b - a)) / 60.0, using GENERATED ALWAYS AS (...) STORED
       in place of MSSQL's PERSISTED computed column.

   All identifiers are double-quoted to preserve exact MSSQL casing
   (e.g. "EmployeeID", "CreateAt") — remember every reference in application
   SQL must use the same quoting, since unquoted identifiers fold to
   lowercase in Postgres.

   SCOPE: schema only — no seed/data rows. Tables are created in FK-dependency
   order (members/Employee/projects before users, users before
   file_folders/files/security_events/user_security_state/worklogs).

   REQUIRES: PostgreSQL 12+ (GENERATED ALWAYS AS ... STORED) and
   PostgreSQL 10+ (GENERATED ... AS IDENTITY). Not yet exercised against a
   running Postgres instance — verify the worklogs generated columns with a
   test row (start_time='08:00', end_time='17:30' should give hours=8.00,
   overtime_hours=0.00, regular_hours=8.00) before trusting this in prod.
============================================================================ */

BEGIN;

/* =========================
   ALLOWANCE
========================= */
CREATE TABLE IF NOT EXISTS "Allowance" (
    "ID"          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "log_date"    DATE DEFAULT CURRENT_DATE,
    "EmployeeID"  CHAR(5),
    "ProjectCode" CHAR(30),
    "Description" CHAR(500),
    "type"        CHAR(1),
    "CreateAt"    TIMESTAMP DEFAULT now(),
    "UpdateAt"    TIMESTAMP DEFAULT now(),
    "IsEditRow"   BOOLEAN DEFAULT TRUE
);

/* =========================
   EMPLOYEE
========================= */
CREATE TABLE IF NOT EXISTS "Employee" (
    "ID"              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "EmployeeID"      VARCHAR(5)   NOT NULL,
    "EmployeeName"    VARCHAR(150) NOT NULL,
    "Department"      VARCHAR(100),
    "Position"        VARCHAR(100),
    "Level"           VARCHAR(10),
    "JG"              VARCHAR(20),
    "CreateAt"        TIMESTAMP DEFAULT now(),
    "UpdateAt"        TIMESTAMP DEFAULT now(),
    "AvatarPath"      VARCHAR(300),
    "AvatarMime"      VARCHAR(100),
    "AvatarUpdatedAt" TIMESTAMP,
    "Operation"       VARCHAR(50)
);

/* =========================
   PROJECT AND BUDGET
========================= */
CREATE TABLE IF NOT EXISTS "ProjectAndBudget" (
    "ID"                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ProjectCode"       CHAR(50),
    "Budget"            CHAR(50),
    "Description"       CHAR(500),
    "CreateAt"          TIMESTAMP DEFAULT now(),
    "UpdateAt"          TIMESTAMP DEFAULT now(),
    "Status"            VARCHAR(20) DEFAULT 'Initiative',
    "ProjectDepartment" VARCHAR(20)
);

/* =========================
   HOLIDAY
   NOTE: "ID" is NOT auto-incrementing in the source schema — inserts must
   supply an explicit ID, same as the MSSQL original.
========================= */
CREATE TABLE IF NOT EXISTS "holiday" (
    "ID"          INTEGER PRIMARY KEY,
    "date"        DATE,
    "description" CHAR(200)
);

/* =========================
   MEMBERS (legacy, kept for FK compatibility — see CLAUDE.md §4)
========================= */
CREATE TABLE IF NOT EXISTS "members" (
    "id"         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "name"       VARCHAR(200) NOT NULL,
    "department" VARCHAR(100),
    "staff_id"   VARCHAR(50)
);

/* =========================
   MEMBER SKILLS
========================= */
CREATE TABLE IF NOT EXISTS "member_skills" (
    "id"         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "member_id"  INTEGER,
    "name"       VARCHAR(120) NOT NULL,
    "level"      SMALLINT NOT NULL,
    "created_at" TIMESTAMP NOT NULL DEFAULT now(),
    "updated_at" TIMESTAMP NOT NULL DEFAULT now(),
    "EmployeeID" VARCHAR(5),
    CONSTRAINT "CK_member_skills_level" CHECK ("level" BETWEEN 1 AND 5)
