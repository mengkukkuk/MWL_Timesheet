/* =========================
   WORKLOGS
========================= */
CREATE TABLE IF NOT EXISTS worklogs (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id         INTEGER REFERENCES members (id),
    employeeid        VARCHAR(5),
    log_date          DATE NOT NULL,
    project           VARCHAR(200),
    projectdepartment VARCHAR(50),
    task              VARCHAR(500),
    start_time        TIME,
    end_time          TIME,

    -- hours: (end - start) minus the 12:00-13:00 lunch overlap.
    hours NUMERIC(5,2) GENERATED ALWAYS AS (
        CASE
            WHEN start_time IS NOT NULL AND end_time IS NOT NULL AND end_time >= start_time
            THEN (
                EXTRACT(EPOCH FROM (end_time - start_time)) / 60.0
                - CASE
                    WHEN start_time < TIME '13:00:00' AND end_time > TIME '12:00:00'
                    THEN EXTRACT(EPOCH FROM (LEAST(end_time, TIME '13:00:00')
                                             - GREATEST(start_time, TIME '12:00:00'))) / 60.0
                    ELSE 0
                  END
            ) / 60.0
        END
    ) STORED,

    -- overtime_hours: minutes before 08:30 plus minutes after 17:30.
    overtime_hours NUMERIC(5,2) GENERATED ALWAYS AS (
        CASE
            WHEN start_time IS NOT NULL AND end_time IS NOT NULL AND end_time >= start_time
            THEN (
                (CASE WHEN start_time < TIME '08:30:00'
                      THEN EXTRACT(EPOCH FROM (LEAST(end_time, TIME '08:30:00') - start_time)) / 60.0
                      ELSE 0 END)
                +
                (CASE WHEN end_time > TIME '17:30:00'
                      THEN EXTRACT(EPOCH FROM (end_time - GREATEST(start_time, TIME '17:30:00'))) / 60.0
                      ELSE 0 END)
            ) / 60.0
        END
    ) STORED,

    status VARCHAR(50)
        CONSTRAINT ck_worklogs_status
        CHECK (status IN ('Man day', 'Pending', 'In Progress', 'Done', 'Leave')),
    note   VARCHAR(1000),

    ot1   NUMERIC(5,2),
    ot3   NUMERIC(5,2),
    ot1_5 NUMERIC(5,2),

    created_at TIMESTAMP DEFAULT now(),
    updated_at TIMESTAMP DEFAULT now(),

    description VARCHAR(200),
    iseditrow   BOOLEAN NOT NULL DEFAULT TRUE,

    -- regular_hours: the 08:30-17:30 portion of the entry, minus lunch overlap.
    regular_hours NUMERIC(5,2) GENERATED ALWAYS AS (
        CASE
            WHEN start_time IS NOT NULL AND end_time IS NOT NULL
                 AND end_time > TIME '08:30:00' AND start_time < TIME '17:30:00'
            THEN (
                EXTRACT(EPOCH FROM (LEAST(end_time, TIME '17:30:00')
                                    - GREATEST(start_time, TIME '08:30:00'))) / 60.0
                - CASE
                    WHEN start_time < TIME '13:00:00' AND end_time > TIME '12:00:00'
                    THEN EXTRACT(EPOCH FROM (LEAST(end_time, TIME '13:00:00')
                                             - GREATEST(start_time, TIME '12:00:00'))) / 60.0
                    ELSE 0
                  END
            ) / 60.0
            ELSE 0
        END
    ) STORED,

    is_allowance       BOOLEAN NOT NULL DEFAULT FALSE,
    allowance_overtime NUMERIC(5,2)
);

CREATE INDEX IF NOT EXISTS ix_worklogs_employee_date
    ON worklogs (employeeid, log_date);

CREATE INDEX IF NOT EXISTS ix_worklogs_project
    ON worklogs (project)
    WHERE project IS NOT NULL;

CREATE INDEX IF NOT EXISTS ix_worklogs_log_date
    ON worklogs (log_date)
    INCLUDE (employeeid, project, status);

