/* =========================
   FILE SHARE
========================= */
CREATE TABLE IF NOT EXISTS "file_folders" (
    "id"            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "name"          VARCHAR(200) NOT NULL,
    "parent_id"     INTEGER REFERENCES "file_folders"("id"),
    "created_by"    INTEGER REFERENCES "users"("id"),
    "created_at"    TIMESTAMP DEFAULT now(),
    "is_classified" BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT "UQ_file_folders_parent_name" UNIQUE ("parent_id", "name")
);

CREATE TABLE IF NOT EXISTS "files" (
    "id"            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "folder_id"     INTEGER REFERENCES "file_folders"("id"),
    "original_name" VARCHAR(400) NOT NULL,
    "stored_name"   VARCHAR(200) NOT NULL,
    "size_bytes"    BIGINT NOT NULL,
    "mime_type"     VARCHAR(200),
    "sha256"        CHAR(64),
    "uploaded_by"   INTEGER REFERENCES "users"("id"),
    "uploaded_at"   TIMESTAMP DEFAULT now(),
    "is_classified" BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT "UQ_files_stored_name" UNIQUE ("stored_name")
);

CREATE INDEX IF NOT EXISTS "IX_files_folder" ON "files" ("folder_id");

/* =========================
   SECURITY EVENTS
========================= */
CREATE TABLE IF NOT EXISTS "security_events" (
    "id"         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "user_id"    INTEGER REFERENCES "users"("id"),
    "username"   VARCHAR(100),
    "event_type" VARCHAR(100) NOT NULL,
    "ip_address" VARCHAR(100),
    "user_agent" VARCHAR(500),
    "detail"     TEXT,
    "created_at" TIMESTAMP DEFAULT now()
);

/* =========================
   USER SECURITY STATE
========================= */
CREATE TABLE IF NOT EXISTS "user_security_state" (
    "user_id"                   INTEGER PRIMARY KEY REFERENCES "users"("id"),
    "failed_login_count"        INTEGER NOT NULL DEFAULT 0,
    "failed_login_window_start" TIMESTAMP,
    "locked_until"              TIMESTAMP,
    "unlock_token_hash"         VARCHAR(256),
    "unlock_token_expires_at"   TIMESTAMP,
    "last_unlock_email_sent_at" TIMESTAMP,
    "updated_at"                TIMESTAMP NOT NULL DEFAULT now(),
    "reset_token_hash"          VARCHAR(64),
    "reset_token_expires_at"    TIMESTAMP,
    "last_reset_email_sent_at"  TIMESTAMP
);

/* =========================
   WORKLOGS
========================= */
CREATE TABLE IF NOT EXISTS "worklogs" (
    "id"                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "member_id"         INTEGER REFERENCES "members"("id"),
    "EmployeeID"        VARCHAR(5),
    "log_date"          DATE NOT NULL,
    "project"           VARCHAR(200),
    "ProjectDepartment" VARCHAR(20),
    "task"              VARCHAR(500),
    "start_time"        TIME,
    "end_time"          TIME,

    -- hours: (end - start) minus lunch overlap (12:00-13:00).
    "hours" NUMERIC(5,2) GENERATED ALWAYS AS (
        CASE
            WHEN "start_time" IS NOT NULL AND "end_time" IS NOT NULL AND "end_time" >= "start_time"
            THEN (
                EXTRACT(EPOCH FROM ("end_time" - "start_time")) / 60.0
                - CASE
                    WHEN "start_time" < TIME '13:00:00' AND "end_time" > TIME '12:00:00'
                    THEN EXTRACT(EPOCH FROM (LEAST("end_time", TIME '13:00:00') - GREATEST("start_time", TIME '12:00:00'))) / 60.0
                    ELSE 0
                  END
            )::NUMERIC(5,2)
        END
    ) STORED,

    -- overtime_hours: minutes before 08:30 plus minutes after 17:30.
    "overtime_hours" NUMERIC(5,2) GENERATED ALWAYS AS (
        CASE
            WHEN "start_time" IS NOT NULL AND "end_time" IS NOT NULL AND "end_time" >= "start_time"
            THEN (
                (CASE WHEN "start_time" < TIME '08:30:00'
                      THEN EXTRACT(EPOCH FROM (LEAST("end_time", TIME '08:30:00') - "start_time")) / 60.0
                      ELSE 0 END)
                +
                (CASE WHEN "end_time" > TIME '17:30:00'
                      THEN EXTRACT(EPOCH FROM ("end_time" - GREATEST("start_time", TIME '17:30:00'))) / 60.0
                      ELSE 0 END)
            )::NUMERIC(5,2)
        END
    ) STORED,

    "status" VARCHAR(50)
        CONSTRAINT "CK__worklogs__status__534D60F1"
        CHECK ("status" IN ('Man day', 'Pending', 'In Progress', 'Done', 'Leave')),
    "note"   VARCHAR(1000),

    "OT1"   NUMERIC(18,2),
    "OT3"   NUMERIC(18,2),
    "OT1_5" NUMERIC(18,2),

    "created_at" TIMESTAMP DEFAULT now(),
    "updated_at" TIMESTAMP DEFAULT now(),

    "Description" CHAR(500),
    "IsEditRow"   BOOLEAN DEFAULT TRUE,

    -- regular_hours: portion of work inside 08:30-17:30 minus lunch overlap.
    "regular_hours" NUMERIC(5,2) GENERATED ALWAYS AS (
        CASE
            WHEN "start_time" IS NOT NULL AND "end_time" IS NOT NULL
                 AND "end_time" > TIME '08:30:00' AND "start_time" < TIME '17:30:00'
            THEN (
                EXTRACT(EPOCH FROM (LEAST("end_time", TIME '17:30:00') - GREATEST("start_time", TIME '08:30:00'))) / 60.0
                - CASE
                    WHEN "start_time" < TIME '13:00:00' AND "end_time" > TIME '12:00:00'
                    THEN EXTRACT(EPOCH FROM (LEAST("end_time", TIME '13:00:00') - GREATEST("start_time", TIME '12:00:00'))) / 60.0
                    ELSE 0
                  END
            )::NUMERIC(5,2)
            ELSE 0
        END
    ) STORED,

    "is_allowance"       BOOLEAN NOT NULL DEFAULT FALSE,
    "allowance_overtime" NUMERIC(18,2) DEFAULT 0.00
);

CREATE INDEX IF NOT EXISTS "IX_worklogs_employee_date" ON "worklogs" ("EmployeeID", "log_date");

